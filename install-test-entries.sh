#!/bin/bash

#
# install-test-entries.sh - dev/test helper for the SplashBootManager
#
# ----------------
#
# Prepares a built boot-manager partition for a boot test:
#
#   1. snapshots the kernels/initramfs of the OSes installed on THIS machine
#      (Debian host + SplashOS distro install) into the boot tree, so the
#      manager can kexec them from its own read-only root
#   2. writes the BLS boot tree (loader.conf + loader/entries/*.conf, the
#      format parsed by src/bls.rs)
#   3. appends a "Splash Boot Manager (dev)" menuentry to the host GRUB
#      (/etc/grub.d/40_custom + update-grub) so the partition can be booted
#
# This is MACHINE-SPECIFIC data, so it deliberately lives here and not in the
# canonical edition config (configuration repo). The builder wipes the target
# partition on a fresh build -> re-run this after every (re)build.
#
# The manager itself is not packaged yet (phase 1 dev init); the default
# entry is kexeced by /sbin/init on the target after the loader.conf timeout.
#
# Usage:
#   sudo ./install-test-entries.sh [boot-dir] [splashos-root] [--skip-grub]
#
#   boot-dir      the built boot-manager partition mount   (default /mnt/bootmanager)
#   splashos-root the mounted SplashOS distro install       (default /mnt/splashos)
#   --skip-grub   only refresh the boot tree, leave GRUB alone
#

set -e

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

if [ "$EUID" -ne 0 ]; then
	echo "ERROR: please run this as root (it writes to the boot tree and /etc/grub.d)." >&2
	exit 2
fi

boot_dir="${1:-/mnt/bootmanager}"
splash_root="${2:-/mnt/splashos}"
skip_grub=false
for arg in "$@"; do
	case "$arg" in
		--skip-grub) skip_grub=true ;;
	esac
done

if [ ! -d "$boot_dir" ]; then
	echo "ERROR: boot dir $boot_dir does not exist (is the partition mounted?)" >&2
	exit 1
fi

uuid_of() {
	findmnt -nro UUID "$1"
}

partuuid_of() {
	lsblk -nro PARTUUID "$(findmnt -nro SOURCE "$1")"
}

boot_dir=$(realpath "$boot_dir")
splash_root=$(realpath "$splash_root")

# Install the dev boot core (superkey probe + /sbin/init) straight from the
# edition config in the configuration repo, the same way the build runs it.
edition_file="$SCRIPT_DIR/../configuration/edition-packages/${edition_release:-0.0.1-dev}/${edition_name:-bootloader}.yml"

install_boot_tools() {
	local cmd
	cmd=$(yq eval '.build[0].build[-1].commands[0]' "$edition_file")
	echo "Installing boot tools from $edition_file (superkey probe)..."
	splash_partition_root="$boot_dir" eval "$cmd"
	cmd=$(yq eval '.build[-1].commands[0]' "$edition_file")
	echo "Installing the dev init from the edition config..."
	splash_partition_root="$boot_dir" eval "$cmd"
}

# ---------------------------------------------------------------------------
# 0. Install the dev boot core (superkey + dev init) from the edition config
install_boot_tools

# 1. Snapshot this machine's kernels into the boot tree
# ---------------------------------------------------------------------------

# SplashOS: kernel name is hardcoded in BuildScripts/linux, the initramfs is
# generated by dracut as initramfs-$(uname-r-style release).img where the
# release is the /lib/modules directory name.
splash_kver=$(basename "$(ls -d "$splash_root"/lib/modules/* | head -n1)")
splash_vmlinuz=$(ls "$splash_root"/boot/vmlinuz-*splash* | head -n1)
splash_initrd="$splash_root/boot/initramfs-$splash_kver.img"

# Debian: newest non-SplashOS kernel in the host /boot.
deb_vmlinuz=$(ls -1v /boot/vmlinuz-* | grep -v splash | tail -n1)
deb_kver=$(basename "$deb_vmlinuz" | sed 's/^vmlinuz-//')
deb_initrd="/boot/initrd.img-$deb_kver"

for f in "$splash_vmlinuz" "$splash_initrd" "$deb_vmlinuz" "$deb_initrd"; do
	if [ ! -r "$f" ]; then
		echo "ERROR: missing kernel file $f" >&2
		exit 1
	fi
done

splash_uuid=$(uuid_of "$splash_root")
deb_uuid=$(uuid_of /)
bm_uuid=$(uuid_of "$boot_dir")
# Kernel-native root for initramfs-less boots: the SplashOS kernel has no
# initramfs, and the kernel cannot resolve root=UUID=<filesystem-UUID> on its
# own (that needs initramfs tooling) - it panics with
# "VFS: Unable to mount root fs". PARTUUID= IS resolved by the kernel itself.
bm_partuuid=$(partuuid_of "$boot_dir")

[ -n "$splash_uuid" ] || { echo "ERROR: $splash_root is not mounted (no UUID found)" >&2; exit 1; }
[ -n "$deb_uuid" ] || { echo "ERROR: / has no UUID (is the host root mounted?)" >&2; exit 1; }
[ -n "$bm_uuid" ] || { echo "ERROR: $boot_dir is not mounted (no UUID found)" >&2; exit 1; }
[ -n "$bm_partuuid" ] || { echo "ERROR: $boot_dir has no PARTUUID (msdos/GPT table expected)" >&2; exit 1; }

# Boot-manager kernel: from the built partition when it is already there,
# otherwise fall back to the SplashOS kernel name (the boot-manager build
# installs the same hardcoded kernel file name) so the BLS tree + GRUB entry
# can also be written before the first build finished.
bm_vmlinuz=$(basename "$(ls -1 "$boot_dir"/boot/vmlinuz-* 2>/dev/null | head -n1)" 2>/dev/null || true)
if [ -z "$bm_vmlinuz" ] || [ "$bm_vmlinuz" = "vmlinuz-*" ]; then
	bm_vmlinuz=$(basename "$(ls -1 "$splash_root"/boot/vmlinuz-* | head -n1)")
	echo "WARN: no kernel in $boot_dir/boot yet, assuming kernel name $bm_vmlinuz"
fi

echo "SplashOS: $splash_vmlinuz (root UUID $splash_uuid)"
echo "Debian:   $deb_vmlinuz (root UUID $deb_uuid)"

mkdir -pv "$boot_dir/splashos/7.1.8" \
	      "$boot_dir/debian/$deb_kver" \
	      "$boot_dir/loader/entries"

cp -v "$splash_vmlinuz" "$boot_dir/splashos/7.1.8/linux"
cp -v "$splash_initrd" "$boot_dir/splashos/7.1.8/initrd"
cp -v "$deb_vmlinuz" "$boot_dir/debian/$deb_kver/linux"
cp -v "$deb_initrd" "$boot_dir/debian/$deb_kver/initrd"

# ---------------------------------------------------------------------------
# 2. BLS boot tree (parsed by src/bls.rs: "key value" per line, single space
#    after the key; ids sorted by file name)
# ---------------------------------------------------------------------------

cat > "$boot_dir/loader/loader.conf" << EOF
# $BOOT/loader/loader.conf
timeout 5
default splashos-0.0.1*
EOF

cat > "$boot_dir/loader/entries/splashos-0.0.1.conf" << EOF
# SplashOS distro install (kexec target)
title   SplashOS 0.0.1-dev (Kokomi)
linux   /splashos/7.1.8/linux
initrd  /splashos/7.1.8/initrd
options root=UUID=$splash_uuid ro
EOF

cat > "$boot_dir/loader/entries/debian-13-trixie.conf" << EOF
# Debian host install (kexec target)
title   Debian GNU/Linux 13 (trixie)
linux   /debian/$deb_kver/linux
initrd  /debian/$deb_kver/initrd
options root=UUID=$deb_uuid ro quiet
EOF

# A rescue entry that boots the boot-manager root itself to a shell (ro).
# PARTUUID (not filesystem UUID): the bootmanager kernel boots without an
# initramfs, so the kernel itself must resolve the root device.
cat > "$boot_dir/loader/entries/rescue.conf" << EOF
# Rescue shell on the boot-manager root
title   Rescue shell
linux   /boot/$bm_vmlinuz
options root=PARTUUID=$bm_partuuid ro init=/bin/bash
EOF

echo "BLS boot tree written to $boot_dir/loader"

# ---------------------------------------------------------------------------
# 3. Host GRUB entry (boots the boot-manager kernel from its own partition;
#    no initramfs - the root drivers are built into the SplashOS kernel)
# ---------------------------------------------------------------------------

if [ "$skip_grub" = true ]; then
	echo "Skipping GRUB (--skip-grub)."
	exit 0
fi

grub_custom=/etc/grub.d/40_custom
if grep -q "Splash Boot Manager (dev)" "$grub_custom" 2>/dev/null; then
	echo "GRUB entry already present in $grub_custom, skipping."
else
	cat >> "$grub_custom" << EOF

menuentry "Splash Boot Manager (dev)" {
	insmod ext2
	search --no-floppy --fs-uuid --set=root $bm_uuid
	# PARTUUID, not filesystem UUID: the target kernel boots without an
	# initramfs, so only the kernel itself can resolve the root device.
	linux /boot/$bm_vmlinuz root=PARTUUID=$bm_partuuid ro init=/sbin/init
}
EOF
	echo "GRUB entry appended to $grub_custom"
fi

update-grub
echo "Done. Reboot and pick 'Splash Boot Manager (dev)'."
